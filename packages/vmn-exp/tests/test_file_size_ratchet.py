"""Ratchet: no vmn-exp source file grows past its recorded size (CLAUDE.md
"Splitting tasks", ~300 lines per file).

A module of the two vmn_exp src roots over LIMIT lines must be listed in
file_size_known.KNOWN_OVERSIZED and may not exceed its entry; an entry must be
lowered (or removed) in the same commit that shrinks the file. Regenerate:
    python packages/vmn-exp/tests/test_file_size_ratchet.py --regen
"""
import sys
from pathlib import Path

from file_size_known import KNOWN_OVERSIZED
from test_io_boundary import _module_paths

LIMIT = 300
REGEN = "python packages/vmn-exp/tests/test_file_size_ratchet.py --regen"


def line_count(text):
    return len(text.splitlines())


def _oversized():
    found = {}
    for module, path in _module_paths().items():
        lines = line_count(path.read_text())
        if lines > LIMIT:
            found[module] = lines
    return found


def test_limit_helper_counts_lines_of_a_given_text():
    assert line_count("") == 0
    assert line_count("a\nb\n") == 2
    assert line_count("a\nb") == 2
    assert line_count("a\n\n\nb\n") == 4


def test_no_file_exceeds_its_recorded_size():
    over = [
        f"{module}: {lines} lines > cap {KNOWN_OVERSIZED.get(module, LIMIT)}"
        for module, lines in _oversized().items()
        if lines > KNOWN_OVERSIZED.get(module, LIMIT)
    ]
    assert not over, (
        f"A source file grew past its cap; split it (new modules stay under {LIMIT} "
        "lines) instead of raising the cap:\n  " + "\n  ".join(over)
    )


def test_recorded_sizes_are_not_stale():
    actual = _oversized()
    stale = [
        f"{module}: recorded {known} > actual {actual.get(module, 0)}"
        for module, known in KNOWN_OVERSIZED.items()
        if known > actual.get(module, 0)
    ]
    assert not stale, f"A listed file shrank; lower the list with `{REGEN}`:\n  " + "\n  ".join(stale)


def _regen():
    lines = [
        f"# AUTO-GENERATED by: {REGEN}",
        f"# Modules over {LIMIT} lines and their line counts. Entries only go down.",
        "",
        "KNOWN_OVERSIZED = {",
    ]
    lines += [f"    {module!r}: {count}," for module, count in sorted(_oversized().items())]
    lines += ["}", ""]
    out = Path(__file__).parent / "file_size_known.py"
    out.write_text("\n".join(lines))
    print(f"Written: {out}")


if __name__ == "__main__":
    if "--regen" not in sys.argv:
        sys.exit(f"Usage: {REGEN}")
    _regen()
